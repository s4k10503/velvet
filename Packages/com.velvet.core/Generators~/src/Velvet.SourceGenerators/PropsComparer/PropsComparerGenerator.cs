using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using System.Threading;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;
using Velvet.SourceGenerators.Shared;

namespace Velvet.SourceGenerators
{
    /// <summary>
    /// Incremental Source Generator that emits one props comparer per props type of a
    /// <c>[Component(Memoize = true)]</c> method, registered with <c>Velvet.PropsComparerRegistry</c> from a
    /// module initializer. A props type the generator cannot compare member by member exactly as the
    /// runtime's own walk does gets no comparer and keeps that walk.
    /// </summary>
    [Generator(LanguageNames.CSharp)]
    public sealed class PropsComparerGenerator : IIncrementalGenerator
    {
        internal const string HintName = "Velvet.PropsComparers.g.cs";

        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            var models = context.SyntaxProvider
                .ForAttributeWithMetadataName(
                    VelvetWellKnownNames.ComponentAttributeFullName,
                    predicate: static (node, _) => node is Microsoft.CodeAnalysis.CSharp.Syntax.MethodDeclarationSyntax,
                    transform: static (ctx, ct) => BuildModel(ctx, ct))
                .Where(static model => model is not null)
                .Select(static (model, _) => model!.Value)
                .Collect();

            context.RegisterSourceOutput(models, static (spc, all) => Emit(spc, all));
        }

        private static PropsComparerModel? BuildModel(GeneratorAttributeSyntaxContext ctx, CancellationToken ct)
        {
            ct.ThrowIfCancellationRequested();
            if (ctx.TargetSymbol is not IMethodSymbol { IsStatic: true } method || method.Parameters.Length != 1)
            {
                return null;
            }

            if (method.Parameters[0].RefKind != RefKind.None || !IsMemoized(ctx.Attributes))
            {
                return null;
            }

            if (method.Parameters[0].Type is not INamedTypeSymbol propsType)
            {
                return null;
            }

            return PropsComparerBody.TryBuild(ctx.SemanticModel.Compilation, propsType);
        }

        private static bool IsMemoized(ImmutableArray<AttributeData> attributes) =>
            attributes.Any(attribute => attribute.NamedArguments.Any(named =>
                named.Key == "Memoize" && named.Value.Value is true));

        private static void Emit(SourceProductionContext spc, ImmutableArray<PropsComparerModel> models)
        {
            if (models.IsDefaultOrEmpty)
            {
                return;
            }

            var distinct = models
                .GroupBy(model => model.TypeName, StringComparer.Ordinal)
                .Select(group => group.First())
                .OrderBy(model => model.TypeName, StringComparer.Ordinal)
                .ToList();
            spc.AddSource(HintName, SourceText.From(RenderFile(distinct), Encoding.UTF8));
        }

        internal static string RenderFile(IReadOnlyList<PropsComparerModel> models)
        {
            var sb = new SourceBuilder();
            sb.AppendLine("// <auto-generated/>");
            sb.AppendLine("#nullable disable");
            sb.AppendLine();
            sb.AppendLine("namespace Velvet.Generated");
            using (sb.Block())
            {
                sb.AppendLine("internal static class PropsComparers");
                using (sb.Block())
                {
                    AppendRegister(sb, models);
                    for (var i = 0; i < models.Count; i++)
                    {
                        sb.AppendLine();
                        AppendComparer(sb, i, models[i]);
                    }
                }
            }

            return sb.ToString();
        }

        private static void AppendRegister(SourceBuilder sb, IReadOnlyList<PropsComparerModel> models)
        {
            sb.AppendLine("[global::System.Runtime.CompilerServices.ModuleInitializer]");
            sb.AppendLine("internal static void Register()");
            using (sb.Block())
            {
                for (var i = 0; i < models.Count; i++)
                {
                    sb.AppendLine(
                        $"global::{VelvetWellKnownNames.PropsComparerRegistryFullName}." +
                        $"Register(typeof({models[i].TypeName}), Equals{i});");
                }
            }
        }

        private static void AppendComparer(SourceBuilder sb, int index, PropsComparerModel model)
        {
            sb.AppendLine($"private static bool Equals{index}(object prev, object next)");
            using (sb.Block())
            {
                if (model.Checks.Length != 0)
                {
                    sb.AppendLine($"var p = ({model.TypeName})prev;");
                    sb.AppendLine($"var n = ({model.TypeName})next;");
                }

                for (var i = 0; i < model.Checks.Length; i++)
                {
                    sb.AppendLine($"var a{i} = p.{model.Checks[i].Member};");
                    sb.AppendLine($"var b{i} = n.{model.Checks[i].Member};");
                    sb.AppendLine($"if (!{model.Checks[i].Equality})");
                    using (sb.Block())
                    {
                        sb.AppendLine("return false;");
                    }
                }

                sb.AppendLine("return true;");
            }
        }
    }

    internal readonly struct MemberCheck : IEquatable<MemberCheck>
    {
        public MemberCheck(string member, string equality)
        {
            Member = member;
            Equality = equality;
        }

        public string Member { get; }
        public string Equality { get; }

        public bool Equals(MemberCheck other) =>
            string.Equals(Member, other.Member, StringComparison.Ordinal) &&
            string.Equals(Equality, other.Equality, StringComparison.Ordinal);

        public override bool Equals(object? obj) => obj is MemberCheck other && Equals(other);

        public override int GetHashCode() =>
            unchecked(StringComparer.Ordinal.GetHashCode(Member) * 31 + StringComparer.Ordinal.GetHashCode(Equality));
    }

    internal readonly struct PropsComparerModel : IEquatable<PropsComparerModel>
    {
        public PropsComparerModel(string typeName, ImmutableArray<MemberCheck> checks)
        {
            TypeName = typeName;
            Checks = checks;
        }

        public string TypeName { get; }
        public ImmutableArray<MemberCheck> Checks { get; }

        public bool Equals(PropsComparerModel other)
        {
            if (!string.Equals(TypeName, other.TypeName, StringComparison.Ordinal) ||
                Checks.Length != other.Checks.Length)
            {
                return false;
            }

            for (var i = 0; i < Checks.Length; i++)
            {
                if (!Checks[i].Equals(other.Checks[i]))
                {
                    return false;
                }
            }

            return true;
        }

        public override bool Equals(object? obj) => obj is PropsComparerModel other && Equals(other);

        public override int GetHashCode()
        {
            var hash = StringComparer.Ordinal.GetHashCode(TypeName);
            foreach (var check in Checks)
            {
                hash = unchecked(hash * 31 + check.GetHashCode());
            }

            return hash;
        }
    }
}
