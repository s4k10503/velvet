using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Globalization;
using System.Text;
using System.Text.RegularExpressions;

namespace Velvet.StyleTable
{
    /// <summary>
    /// Derives the palette's <c>--color-&lt;hue&gt;-&lt;shade&gt;</c> tokens in <c>_palette.uss</c>, and the table
    /// <c>VelvetPalette</c> resolves an inline colour from, out of the OKLCH colours in <see cref="SourceFileName"/>.
    /// </summary>
    /// <remarks>
    /// USS reads no <c>oklch()</c>, so each colour is converted to sRGB here as CSS Color 4 converts it, through OKLab,
    /// LMS and XYZ, and a channel outside the gamut is clipped, the rule <c>styling-colors.md</c> gives for every colour
    /// outside sRGB. The sheet's <c>:root</c> block is rewritten whole and the rest of the sheet is left as written, so
    /// the bg-, text- and border- rules naming a token stay hand-ordered among the semantic colours.
    /// </remarks>
    internal static class PaletteDerivation
    {
        public const string SourceFileName = "PaletteColors.css";

        public const string SheetFileName = "_palette.uss";

        public const string TableFileName = "VelvetPaletteColors.g.cs";

        private static readonly Regex Declaration = new Regex(
            @"--color-(?<name>[a-z]+-\d+):\s*oklch\((?<l>\d+(?:\.\d+)?)%\s+(?<c>\d+(?:\.\d+)?)\s+(?<h>\d+(?:\.\d+)?|none)\)\s*;");

        private static readonly Regex AnyDeclaration = new Regex(@"--color-[^;]*;?");

        private static readonly Regex RootBlock = new Regex(@":root\s*\{[^}]*\}");

        private const string TableHeader = @"// <auto-generated/>
//
// Derived from Generators~/src/Velvet.StyleTable/PaletteColors.css by Generators~/src/Velvet.StyleTable. Regenerate
// with Generators~/build.py after editing that file; edits made here are overwritten, and
// BundledStyleSheetCensusTests fails if this file no longer matches it.
#nullable disable
using System.Collections.Generic;

namespace Velvet
{
    internal static class VelvetPaletteColors
    {
        // ""<hue>-<shade>"" -> ""#rrggbb"", the sRGB colour _palette.uss declares as --color-<hue>-<shade>.
        internal static readonly Dictionary<string, string> Hex = new Dictionary<string, string>
        {
";

        private const string TableFooter = @"        };
    }
}
";

        public static PaletteDerivationResult Build(string source, string sheet)
        {
            var problems = ImmutableArray.CreateBuilder<UssProblem>();
            var colours = ReadColours(source, problems);
            var root = RootBlock.Match(sheet);
            if (!root.Success)
            {
                problems.Add(new UssProblem(UssProblemCode.MalformedUss,
                    $"{SheetFileName} declares no :root block for the palette tokens to be written into."));
            }
            if (problems.Count > 0)
            {
                return new PaletteDerivationResult(sheet, string.Empty, problems.ToImmutable());
            }

            var tokens = new StringBuilder(":root {\n");
            var table = new StringBuilder(TableHeader);
            foreach (var (name, hex) in colours)
            {
                tokens.Append("    --color-").Append(name).Append(": ").Append(hex).Append(";\n");
                table.Append("            [\"").Append(name).Append("\"] = \"").Append(hex).Append("\",\n");
            }
            tokens.Append('}');
            table.Append(TableFooter);
            var rewritten = sheet.Substring(0, root.Index) + tokens + sheet.Substring(root.Index + root.Length);
            return new PaletteDerivationResult(rewritten, table.ToString(), problems.ToImmutable());
        }

        /// <summary>
        /// Every colour the source declares, in its order. A declaration the pattern does not read is a problem
        /// rather than a skip, or a colour written another way would drop out of the palette unnoticed.
        /// </summary>
        private static List<(string Name, string Hex)> ReadColours(
            string source, ImmutableArray<UssProblem>.Builder problems)
        {
            var colours = new List<(string, string)>();
            foreach (Match written in AnyDeclaration.Matches(source))
            {
                var declaration = Declaration.Match(written.Value);
                if (!declaration.Success || declaration.Index != 0 || declaration.Length != written.Length)
                {
                    problems.Add(new UssProblem(UssProblemCode.MalformedUss,
                        $"'{written.Value}' is not --color-<hue>-<shade>: oklch(<L>% <C> <H>);"));
                    continue;
                }
                var hue = declaration.Groups["h"].Value;
                colours.Add((declaration.Groups["name"].Value, ToSrgbHex(
                    Number(declaration.Groups["l"].Value) / 100.0,
                    Number(declaration.Groups["c"].Value),
                    hue == "none" ? 0.0 : Number(hue))));
            }
            if (colours.Count == 0 && problems.Count == 0)
            {
                problems.Add(new UssProblem(UssProblemCode.MalformedUss, $"{SourceFileName} declares no colour."));
            }
            return colours;
        }

        private static double Number(string text) => double.Parse(text, NumberStyles.Float, CultureInfo.InvariantCulture);

        /// <summary>An OKLCH colour as <c>#rrggbb</c>, each channel clipped to the sRGB gamut.</summary>
        internal static string ToSrgbHex(double lightness, double chroma, double hueDegrees)
        {
            var hue = hueDegrees * Math.PI / 180.0;
            var a = chroma * Math.Cos(hue);
            var b = chroma * Math.Sin(hue);

            var l = Cube(lightness + 0.3963377773761749 * a + 0.2158037573099136 * b);
            var m = Cube(lightness - 0.1055613458156586 * a - 0.0638541728258133 * b);
            var s = Cube(lightness - 0.0894841775298119 * a - 1.2914855480194092 * b);

            var x = 1.2268798758459243 * l - 0.5578149944602171 * m + 0.2813910456659647 * s;
            var y = -0.0405757452148008 * l + 1.1122868032803170 * m - 0.0717110580655164 * s;
            var z = -0.0763729366746601 * l - 0.4214933324022432 * m + 1.5869240198367816 * s;

            var red = 12831.0 / 3959.0 * x - 329.0 / 214.0 * y - 1974.0 / 3959.0 * z;
            var green = -851781.0 / 878810.0 * x + 1648619.0 / 878810.0 * y + 36519.0 / 878810.0 * z;
            var blue = 705.0 / 12673.0 * x - 2585.0 / 12673.0 * y + 705.0 / 667.0 * z;

            return "#" + Channel(red) + Channel(green) + Channel(blue);
        }

        private static double Cube(double value) => value * value * value;

        private static string Channel(double linear)
        {
            var magnitude = Math.Abs(linear);
            var encoded = magnitude > 0.0031308
                ? Math.Sign(linear) * (1.055 * Math.Pow(magnitude, 1.0 / 2.4) - 0.055)
                : 12.92 * linear;
            var clipped = Math.Min(1.0, Math.Max(0.0, encoded));
            return ((int)Math.Round(clipped * 255.0, MidpointRounding.AwayFromZero)).ToString("x2", CultureInfo.InvariantCulture);
        }
    }

    internal readonly struct PaletteDerivationResult
    {
        public PaletteDerivationResult(string emittedSheet, string emittedTable, ImmutableArray<UssProblem> problems)
        {
            EmittedSheet = emittedSheet;
            EmittedTable = emittedTable;
            Problems = problems;
        }

        /// <summary>The palette sheet with its <c>:root</c> block rewritten; the sheet unchanged on a problem.</summary>
        public string EmittedSheet { get; }

        public string EmittedTable { get; }

        public ImmutableArray<UssProblem> Problems { get; }
    }
}
